#!/usr/bin/env node
// v37 layout spacing and shared node-editing regression checks.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const source=read('mindmap/state-layout.js');
const start=source.indexOf('function mapLayout(root,collapsed){');
const end=source.indexOf('function mapStatusColor(n){');
assert.ok(start>=0&&end>start,'Missing layout implementation');
const pStart=source.indexOf('function positionMapRows(state){');
const pEnd=source.indexOf('function mapBounds(state){');
assert.ok(pStart>=0&&pEnd>pStart,'Missing coordinate calculation');
const functions=source.slice(start,end)+source.slice(pStart,pEnd);
const context=vm.createContext({Set,Math});
vm.runInContext(functions,context);
const check=(rootNode,from,to,desired)=>{
  context.structure=rootNode;
  const rows=vm.runInContext('mapLayout(structure,new Set())',context);
  for(const row of rows.rows)row.el={offsetHeight:70,offsetWidth:205,style:{}};
  context.layout=rows;
  vm.runInContext('positionMapRows(layout)',context);
  const index=Object.fromEntries(rows.rows.map(row=>[row.path,row]));
  const gap=index[to].y-(index[from].y+index[from].height);
  assert.equal(gap,desired,`${from} to ${to}: expected ${desired}px, got ${gap}px`);
};
const leaf=(path)=>({path,children:[]});
const block=(name)=>({path:name,children:[0,1,2].map(i=>leaf(`${name}-${i}`))});
const main={path:'root',children:[block('a'),block('b'),block('c'),block('d')]};
check(main,'a-0','a-1',30);
check(main,'b-1','b-2',30);
check(main,'a-2','b-0',64);
check(main,'b-2','c-0',64);
const nested={path:'root',children:[{path:'a',children:[{path:'a0',children:[leaf('a00'),leaf('a01')]},{path:'a1',children:[]}]}]};
check(nested,'a00','a01',18);
const deeper={path:'root',children:[{path:'a',children:[{path:'a0',children:[{path:'a00',children:[leaf('a000'),leaf('a001')]}]}]}]};
check(deeper,'a000','a001',12);
const dialogs=read('ui/dialogs.js');
const nodeEditor=dialogs.split('function editNode(path){')[1]?.split('function navigateLink(',1)[0];
assert.ok(nodeEditor,'Node editing function absent');
assert.ok(!nodeEditor.includes('isKanbanTicket'),'Editor must not special-case Kanban');
assert.match(nodeEditor,/<label for="nodeTitle">Knoten bearbeiten<\/label>/);
assert.match(nodeEditor,/id="nodeStatus"/);
assert.match(nodeEditor,/status:\$\('#nodeStatus'\)\.value\|\|null/);
assert.equal(JSON.parse(read('module-manifest.json')).version,'v48');
assert.match(read('sw.js'),/const VERSION='mindfagg-v48'/);
console.log('PASS: v37 sibling spacing 30/18/12px, parent-block spacing 64px, shared node editor and v38 PWA version');
